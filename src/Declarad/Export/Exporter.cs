using System.Text;
using Declarad.Directory;
using Declarad.Hcl;
using Declarad.Hcl.Values;
using Declarad.Resources;
using Declarad.Resources.Dns;
using Declarad.Resources.Schema;

namespace Declarad.Export
{
    /// <summary>
    /// Generates configuration from existing directory objects. Paths, members and manager links to other
    /// exported objects become references (<c>ou.sales.dn</c>), and values equal to defaults are omitted.
    /// Run <c>declarad plan --adopt</c> afterwards to take the objects under management.
    /// </summary>
    public sealed class Exporter
    {
        private const string NotCritical = "(!(isCriticalSystemObject=TRUE))";

        /// <summary>Types exported when none are requested. Containers are opt-in because AD has many system ones.</summary>
        public static IReadOnlyList<ResourceType> DefaultTypes { get; } = ResourceRegistry.All
            .Where(t => t is not ContainerResource && t is not GroupMembershipResource && t is not DnsZoneResource && t is not DnsRecordResource)
            .ToList();

        /// <summary>Connection name written into every block when it is not the default one.</summary>
        public string Connection { get; init; } = State.StateFile.DefaultConnection;

        /// <summary>Also export DNS records that clients registered dynamically (skipped by default).</summary>
        public bool IncludeDynamicDns { get; init; }

        private readonly IDirectory _directory;
        private readonly SchemaContext _ctx;
        private readonly Dictionary<string, string> _refByDn = new(StringComparer.Ordinal);

        public Exporter(IDirectory directory)
        {
            _directory = directory;
            _ctx = new SchemaContext(directory.DomainName, directory.BaseDn);
        }

        private sealed record Item(ResourceType Type, string Label, DirectoryObject Obj, Dictionary<string, Value> Attrs);

        public string Export(string? baseDn, IReadOnlyCollection<ResourceType> types)
        {
            string root = baseDn ?? _directory.BaseDn;
            var items = new List<Item>();
            var labels = new HashSet<string>(StringComparer.Ordinal);
            foreach (var type in ResourceRegistry.All.Where(t => types.Contains(t) && t is not AttachmentType))
            {
                string searchRoot = baseDn ?? type.DefaultSearchBase(_directory);
                var objects = _directory.Search(searchRoot, $"(&{type.Filter}{NotCritical})", subtree: true, type.LdapAttributes)
                    .Where(type.Matches)
                    .ToList();
                if (type.NeedsSecurityDescriptor)
                {
                    objects = objects.Select(o => _directory.GetByDn(o.Dn, type.LdapAttributes, true) ?? o).ToList();
                }
                foreach (var obj in objects.OrderBy(o => Dn.Depth(o.Dn)).ThenBy(o => o.Dn, StringComparer.OrdinalIgnoreCase))
                {
                    var attrs = type.Read(obj, _directory);
                    string label = UniqueLabel(type.Name, V.Str(attrs.GetValueOrDefault(type.LabelAttribute ?? "name", Value.Null)) ?? "item", labels);
                    items.Add(new Item(type, label, obj, attrs));
                    _refByDn[Dn.Normalize(obj.Dn)] = $"{type.Name}.{label}.dn";
                }
            }

            var sb = new StringBuilder();
            sb.AppendLine($"# Generated by 'declarad export' from {root} on {DateTime.UtcNow:yyyy-MM-dd}.");
            sb.AppendLine("# Review, then run 'declarad plan --adopt' to take these objects under management.");
            foreach (var item in items)
            {
                sb.AppendLine();
                WriteBlock(sb, item);
            }
            if (types.Contains(ResourceRegistry.GpoLink))
            {
                WriteGpoLinks(sb, root, items, labels);
            }
            if (types.Contains(ResourceRegistry.DnsRecord))
            {
                WriteDnsRecords(sb, items.Where(i => i.Type is DnsZoneResource), labels);
            }
            return sb.ToString();
        }

        private static string UniqueLabel(string type, string name, HashSet<string> used)
        {
            string label = HclWriter.ToLabel(name);
            string candidate = label;
            for (int i = 2; !used.Add($"{type}.{candidate}"); i++)
            {
                candidate = $"{label}_{i}";
            }
            return candidate;
        }

        private void WriteBlock(StringBuilder sb, Item item)
        {
            var lines = new List<(string Name, string Expr)>();
            Value Get(string name) => item.Attrs.GetValueOrDefault(name, Value.Null);

            foreach (var spec in item.Type.Schema)
            {
                if (spec.Sensitive || spec.CreateOnly)
                {
                    continue;
                }
                var value = Get(spec.Name);
                if (spec.Name == item.Type.LabelAttribute)
                {
                    if (V.Str(value) != item.Label)
                    {
                        lines.Add((spec.Name, value.ToHcl()));
                    }
                    continue;
                }
                if (spec.Name == "groups" && spec.Additive)
                {
                    // Memberships of exported groups are written on the group; keep the rest here.
                    var external = V.List(value).Where(g => !_refByDn.ContainsKey(Dn.Normalize(g))).ToList();
                    if (external.Count > 0)
                    {
                        lines.Add((spec.Name, FormatList(external, spec.IsDn)));
                    }
                    continue;
                }

                var defaultValue = spec.ResolveDefault(Get, _ctx);
                if (spec.Type == AttrType.StringList)
                {
                    var items = V.List(value);
                    bool same = items.OrderBy(x => x).SequenceEqual(V.List(defaultValue).OrderBy(x => x));
                    // Authoritative lists are written even when empty, so the export manages them exactly.
                    if (!same || (spec.Name == "members" && !value.IsNull))
                    {
                        lines.Add((spec.Name, FormatList(items, spec.IsDn)));
                    }
                    continue;
                }

                // A flag without a default (e.g. smartcard_required) is unmanaged unless set; only export it when on.
                if (spec.Type == AttrType.Bool && defaultValue.IsNull && V.Bool(value) == false)
                {
                    continue;
                }
                bool isDefault = spec.IsDn ? Dn.AreEqual(V.Str(value), V.Str(defaultValue)) : value.Equals(defaultValue);
                if ((V.IsEmpty(value) && V.IsEmpty(defaultValue)) || isDefault)
                {
                    continue;
                }
                lines.Add((spec.Name, value.IsNull ? "null" : spec.IsDn ? Reference(V.Str(value)!) : value.ToHcl()));
            }
            WriteLines(sb, item.Type.Name, item.Label, lines);
        }

        private void WriteLines(StringBuilder sb, string type, string label, List<(string Name, string Expr)> lines, string? comment = null)
        {
            if (Connection != State.StateFile.DefaultConnection)
            {
                lines = lines.Append(("connection", $"connection.{Connection}")).ToList();
            }
            sb.AppendLine($"{type} {HclWriter.Quote(label)} {{{(comment != null ? " # " + comment : "")}");
            int width = lines.Where(l => !l.Expr.Contains('\n')).Select(l => l.Name.Length).DefaultIfEmpty(0).Max();
            foreach (var (name, expr) in lines)
            {
                sb.AppendLine($"  {name.PadRight(expr.Contains('\n') ? 0 : width)} = {expr}");
            }
            sb.AppendLine("}");
        }

        private void WriteGpoLinks(StringBuilder sb, string root, List<Item> items, HashSet<string> labels)
        {
            var targets = items.Where(i => i.Type is OuResource).Select(i => (Dn: i.Obj.Dn, Label: i.Label)).ToList();
            if (Dn.AreEqual(root, _directory.BaseDn))
            {
                targets.Insert(0, (_directory.BaseDn, "domain"));
            }
            var names = new Dictionary<string, string?>(StringComparer.Ordinal);
            foreach (var (dn, targetLabel) in targets)
            {
                var obj = _directory.GetByDn(dn, new[] { "gPLink" });
                foreach (var link in GpoLinkResource.ReadLinks(obj?.Get("gPLink")))
                {
                    if (!names.TryGetValue(link.Gpo, out var gpoName))
                    {
                        gpoName = _directory.Search($"CN=Policies,CN=System,{_directory.BaseDn}", $"(cn={Dn.EscapeFilterValue(link.Gpo)})", subtree: false, new[] { "displayName" })
                            .FirstOrDefault()?.Get("displayName");
                        names[link.Gpo] = gpoName;
                    }
                    var lines = new List<(string, string)>
                    {
                        ("gpo", HclWriter.Quote(link.Gpo)),
                        ("target", Reference(dn)),
                        ("order", link.Order.ToString()),
                    };
                    if (!link.Enabled)
                    {
                        lines.Add(("enabled", "false"));
                    }
                    if (link.Enforced)
                    {
                        lines.Add(("enforced", "true"));
                    }
                    sb.AppendLine();
                    WriteLines(sb, "gpo_link", UniqueLabel("gpo_link", $"{targetLabel}_{gpoName ?? link.Gpo}", labels), lines, gpoName != null ? $"GPO: {gpoName}" : null);
                }
            }
        }

        private void WriteDnsRecords(StringBuilder sb, IEnumerable<Item> zones, HashSet<string> labels)
        {
            foreach (var zone in zones)
            {
                string zoneName = V.Str(zone.Attrs["name"])!;
                foreach (var node in _directory.Search(zone.Obj.Dn, "(objectClass=dnsNode)", subtree: false, new[] { "dnsRecord", "dNSTombstoned" })
                             .OrderBy(n => n.Dn, StringComparer.OrdinalIgnoreCase))
                {
                    if (string.Equals(node.Get("dNSTombstoned"), "TRUE", StringComparison.OrdinalIgnoreCase) || !node.Binary.TryGetValue("dnsRecord", out var values))
                    {
                        continue;
                    }
                    string name = Dn.First(node.Dn).Value.ToLowerInvariant();
                    var records = values.Select(DnsCodec.Decode).Where(r => IncludeDynamicDns || !r.IsDynamic).ToList();
                    foreach (var set in records.GroupBy(r => r.TypeName))
                    {
                        // The zone resource manages the apex SOA and NS records.
                        if (set.Key == "SOA" || (name == "@" && set.Key == "NS") || !DnsCodec.Types.ContainsKey(set.Key))
                        {
                            continue;
                        }
                        bool hasNames = set.Key is "CNAME" or "NS" or "PTR" or "MX" or "SRV";
                        var data = set.Select(r => DnsCodec.DecodeData(r.Type, r.Data)).Select(d => hasNames ? Relative(d, zoneName) : d).Order(StringComparer.Ordinal).ToList();
                        var lines = new List<(string, string)>
                        {
                            ("zone", $"dns_zone.{zone.Label}.name"),
                            ("name", HclWriter.Quote(name)),
                            ("type", HclWriter.Quote(set.Key)),
                            ("records", data.Count == 1 ? $"[{HclWriter.Quote(data[0])}]" : "[\n" + string.Concat(data.Select(d => $"    {HclWriter.Quote(d)},\n")) + "  ]"),
                        };
                        if (set.First().Ttl != 3600)
                        {
                            lines.Add(("ttl", set.First().Ttl.ToString()));
                        }
                        if (!string.Equals(V.Str(zone.Attrs["replication_scope"]), "domain", StringComparison.Ordinal))
                        {
                            lines.Add(("replication_scope", zone.Attrs["replication_scope"].ToHcl()));
                        }
                        sb.AppendLine();
                        WriteLines(sb, "dns_record", UniqueLabel("dns_record", $"{zone.Label}_{(name == "@" ? "apex" : name)}_{set.Key}", labels), lines);
                    }
                }
            }
        }

        /// <summary>Shortens names inside the zone to the relative form used in configuration ("mail.corp.local." becomes "mail").</summary>
        private static string Relative(string text, string zone)
        {
            string suffix = "." + zone + ".";
            return string.Join(' ', text.Split(' ').Select(part =>
                part.EndsWith(suffix, StringComparison.Ordinal) ? part[..^suffix.Length] : part == zone + "." ? "@" : part));
        }

        private string Reference(string dn) => _refByDn.TryGetValue(Dn.Normalize(dn), out var r) ? r : HclWriter.Quote(dn);

        private string FormatList(IReadOnlyList<string> values, bool isDn)
        {
            if (values.Count == 0)
            {
                return "[]";
            }
            var items = values.Select(v => isDn ? Reference(v) : HclWriter.Quote(v)).Order(StringComparer.Ordinal).ToList();
            if (items.Count == 1)
            {
                return $"[{items[0]}]";
            }
            return "[\n" + string.Concat(items.Select(i => $"    {i},\n")) + "  ]";
        }
    }
}
